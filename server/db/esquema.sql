-- ============================================================
-- Esquema de la base de datos de Sistema Stock
-- Ejecutar con: npm run db:migrate
-- ============================================================

BEGIN;

-- Categorías de artículos: Tóner, Periféricos, Cable, etc.
CREATE TABLE IF NOT EXISTS categorias (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre text NOT NULL UNIQUE,
    creado_en timestamptz NOT NULL DEFAULT now()
);

-- Artículos del depósito.
-- stock_actual se mantiene actualizado junto con cada movimiento (en una transacción).
CREATE TABLE IF NOT EXISTS articulos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre text NOT NULL,
    categoria_id integer NOT NULL REFERENCES categorias(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    stock_actual integer NOT NULL DEFAULT 0 CHECK (stock_actual >= 0),
    stock_minimo integer NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    activo boolean NOT NULL DEFAULT true,
    creado_en timestamptz NOT NULL DEFAULT now(),
    actualizado_en timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_articulos_categoria ON articulos(categoria_id);
CREATE INDEX IF NOT EXISTS idx_articulos_activo ON articulos(activo);

-- Edificios / dependencias.
CREATE TABLE IF NOT EXISTS dependencias (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre text NOT NULL UNIQUE,
    activo boolean NOT NULL DEFAULT true,
    creado_en timestamptz NOT NULL DEFAULT now(),
    actualizado_en timestamptz NOT NULL DEFAULT now()
);

-- Oficinas dentro de una dependencia.
CREATE TABLE IF NOT EXISTS oficinas (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre text NOT NULL,
    dependencia_id integer NOT NULL REFERENCES dependencias(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    activo boolean NOT NULL DEFAULT true,
    creado_en timestamptz NOT NULL DEFAULT now(),
    actualizado_en timestamptz NOT NULL DEFAULT now(),
    UNIQUE (dependencia_id, nombre)
);

CREATE INDEX IF NOT EXISTS idx_oficinas_dependencia ON oficinas(dependencia_id);

-- Modelos de impresora. La compatibilidad con un tóner vive en articulo_id.
-- Un modelo tiene un solo tóner; al eliminar el artículo, queda sin asignar.
CREATE TABLE IF NOT EXISTS modelos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marca text NOT NULL,
    modelo text NOT NULL,
    articulo_id integer REFERENCES articulos(id) ON UPDATE CASCADE ON DELETE SET NULL,
    creado_en timestamptz NOT NULL DEFAULT now(),
    actualizado_en timestamptz NOT NULL DEFAULT now(),
    UNIQUE (marca, modelo)
);

CREATE INDEX IF NOT EXISTS idx_modelos_articulo ON modelos(articulo_id);

-- Unidades físicas de impresora, asignadas a una oficina.
CREATE TABLE IF NOT EXISTS unidades (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modelo_id integer NOT NULL REFERENCES modelos(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    nombre text NOT NULL,
    oficina_id integer NOT NULL REFERENCES oficinas(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    ip text,
    estado text NOT NULL DEFAULT 'activa' CHECK (estado IN ('activa', 'inactiva')),
    creado_en timestamptz NOT NULL DEFAULT now(),
    actualizado_en timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_unidades_oficina ON unidades(oficina_id);
CREATE INDEX IF NOT EXISTS idx_unidades_modelo ON unidades(modelo_id);

-- Historial de entradas (al depósito) y salidas (a una oficina).
-- La restricción movimiento_destino garantiza:
--   entrada -> sin oficina
--   salida  -> con oficina
CREATE TABLE IF NOT EXISTS movimientos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    articulo_id integer NOT NULL REFERENCES articulos(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    tipo text NOT NULL CHECK (tipo IN ('entrada', 'salida')),
    cantidad integer NOT NULL CHECK (cantidad > 0),
    oficina_id integer REFERENCES oficinas(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha date NOT NULL DEFAULT CURRENT_DATE,
    creado_en timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT movimiento_destino CHECK (
        (tipo = 'entrada' AND oficina_id IS NULL)
        OR (tipo = 'salida' AND oficina_id IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_movimientos_fecha ON movimientos(fecha DESC);
CREATE INDEX IF NOT EXISTS idx_movimientos_oficina ON movimientos(oficina_id);
CREATE INDEX IF NOT EXISTS idx_movimientos_articulo ON movimientos(articulo_id);

-- Categorías base del sistema. Son datos de configuración, no stock de ejemplo.
INSERT INTO categorias (nombre)
VALUES ('Tóner'), ('Periféricos'), ('Cable')
ON CONFLICT (nombre) DO NOTHING;

COMMIT;
